package com.tutorial;

public class Main {
    public static void main(String[] args) {
        //Membuat variabel
        //setiap isi variabel disimpan di memory
        //nama sebuah variabel disebut identifiers dan tidak boleh memakai kata yang sudah ada di program java
        int a = 12; //pengisian variabel disebut assignment
        System.out.println("a = " + a);

        a = 22;
        System.out.println("a baru = " + a);

        //deklarasi atau pernyataan sebuah variabel dengan tipe datanya
        int b; //ini namanya deklarasi
        // variabel b tidak bisa di print jika tidak ada isinya harus di assignment dulu/input
        b = 22;
        System.out.println("Nilai b = " + b);

        int x=1, y=2, z=3;
        System.out.printf("Multideklarasi variabel dengan identifiers x,y,z");
        System.out.println("x = " + x);
        System.out.println("y = " + y);
        System.out.println("z = " + z);








    }
}
