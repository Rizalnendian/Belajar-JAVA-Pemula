package com.tutorial; //ini nama package

public class Main { //Main disini adalah nama claass nya
    public static void main(String[] args) { //Ini disebut method
        /*Setiap baris perintah yang berbeda,
         diujungnya harus ditambahkan semicolon atau ; */

        System.out.println("Hello World"); //Print huruf haru didalam ""
        System.out.println(1); //print angka
        System.out.println(10 + 6); // print dengan aritmatika
        System.out.println(10 - 6);
        System.out.println(10 * 5);
        System.out.println(10 / 5);
        System.out.println("Pada method di atas terdapat kata public yang artinya class atau method dapat diakses namun jika menjadi private maka class atau method tidak bisa diakses");
    } //ini body method
}//ini body class
